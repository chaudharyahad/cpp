#include <iostream>
using namespace std;

int main()
{
    cout<<"==========================\n";
    cout<<"Airthmetic Operator\n";
    cout<<"==========================\n";

    int a = 10, b = 3;
    // Addition
    cout << "a + b = " << (a + b) << endl;

    // Subtraction
    cout << "a - b = " << (a - b) << endl;

    // Multiplication
    cout << "a * b = " << (a * b) << endl;

    // Division
    cout << "a / b = " << (a / b) << endl;

    // Modulos
    cout << "a % b = " << (a % b) << endl;

    // Increament
    cout << "++a = " << ++a << endl;

    // Decrement
    cout << "b-- = " << b--;

    return 0;
}