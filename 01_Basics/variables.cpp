#include <iostream>

using namespace std;

int main()
{
    // Declare and initialize an integer variable
    int num = 10;

    // Access the variable
    cout << "Initial value: " << num << endl;

    // Update the variable
    num = 20;

    // Print the updated value
    cout << "Updated value: " << num << endl;

    // Declare two integer variables
    int num1 = 100;
    int num2;

    // Assign the value of num1 to num2
    num2 = num1;

    cout << "num1: " << num1 << endl;
    cout << "num2: " << num2 << endl;

    return 0;
}